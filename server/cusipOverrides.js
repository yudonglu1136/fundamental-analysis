export function tickerForHolding({ issuer, cusip }) {
  const byCusip = cusipTickerMap.get(String(cusip || "").trim().toUpperCase());
  if (byCusip) return byCusip;

  const normalized = String(issuer || "")
    .replace(/[.,]/g, "")
    .replace(/\s+/g, " ")
    .trim()
    .toUpperCase();

  return issuerTickerMap.get(normalized) || "";
}
