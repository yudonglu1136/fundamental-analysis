function scenario(
  name: "Bear" | "Base" | "Bull",
  growthDelta: number,
  marginDelta: number,
  wacc: number,
  terminalGrowth: number,
  targetFcfYield: number,
  targetPe: number,
  multipleDelta: number,
  platformMoatAdjustment: number,
  riskAdjustment: number,
  postTradeEconomics: LsegScenarioAssumption["postTradeEconomics"],
  probability: number,
  narrative: string,
): LsegScenarioAssumption {
  const revenueGrowthBySegment = Object.fromEntries(
    Object.entries(baseSegmentGrowth).map(([segment, growth]) => [segment, Math.max(growth + growthDelta, -0.03)]),
  ) as Record<LsegSegment, number>;
  const ebitdaMarginBySegment = Object.fromEntries(
    Object.entries(baseSegmentMargin).map(([segment, margin]) => [segment, Math.max(margin + marginDelta, segment === "Corporate / Other" ? -1 : 0.15)]),
  ) as Record<LsegSegment, number>;
  const evEbitdaMultiples = Object.fromEntries(
    Object.entries(baseMultiples).map(([segment, multiple]) => [segment, Math.max(multiple + multipleDelta, segment === "Corporate / Other" ? -10 : 8)]),
  ) as Record<LsegSegment, number>;

  return {
    scenario: name,
    sourceType: "forecast_assumption",
    revenueGrowthBySegment,
    ebitdaMarginBySegment,
    wacc,
    terminalGrowth,
    targetFcfYield,
    targetPe,
    evEbitdaMultiples,
    evEbitMultiple: targetPe * 0.72,
    platformMoatAdjustment,
    riskAdjustment,
    postTradeEconomics,
    probability,
    narrative,
  };
}

