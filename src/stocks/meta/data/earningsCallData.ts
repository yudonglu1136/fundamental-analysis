import { metaLineage } from "./lineage";

function callLineage(period: string, asOfDate: string, sourceUrl: string, confidence: DataLineage["confidence"] = "medium"): DataLineage {
  return {
    ...metaLineage.q1_2026Transcript,
    sourceName: `Meta ${period} Earnings Call Transcript`,
    sourceUrl,
    period,
    asOfDate,
    retrievedAt: "2026-05-12",
    confidence,
    valuationTreatment: "risk_monitor",
    notes: "Transcript intelligence is used for market-focus trend analysis and model debate tracking. It is not a direct valuation input.",
  };
}

function source(id: string, period: string, asOfDate: string, sourceUrl: string): MetaSource {
  return {
    id,
    title: `Meta ${period} Earnings Call Transcript`,
    url: sourceUrl,
    publisher: "Meta Investor Relations",
    sourceStatus: "management_guidance",
    reportingPeriod: period,
    publishedDate: asOfDate,
    accessedDate: "2026-05-12",
    lineage: callLineage(period, asOfDate, sourceUrl),
    notes: "Official IR transcript URL used as the source anchor; call intelligence is curated into structured model fields.",
  };
}

