  const cjkPattern = /[\u3400-\u9fff]/;
  const orderedTranslations = Object.entries(translations).sort(
    (left, right) => right[0].length - left[0].length,
  );
  const orderedChineseTranslations = Object.entries(chineseTranslations).sort(
    (left, right) => right[0].length - left[0].length,
  );
  function languageCode(value) {
    return String(value || "").trim().toLowerCase().startsWith("zh") ? "zh" : "en";
  }
  let language = languageCode(new URLSearchParams(root.location?.search || "").get("lang"));
  let applying = false;
  const textSources = new WeakMap();
  const attributeSources = new WeakMap();

  function normalizeEnglishPunctuation(value) {
    return value
      .replaceAll("，", ", ")
      .replaceAll("。", ".")
      .replaceAll("；", "; ")
      .replaceAll("：", ": ")
      .replaceAll("、", ", ")
      .replaceAll("（", " (")
      .replaceAll("）", ")")
      .replace(/\s{2,}/g, " ")
      .trim();
  }

  function replaceEnglishPhrase(value, phrase, replacement) {
    const escaped = phrase.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
    const leftBoundary = /^[A-Za-z0-9_]/.test(phrase)
      ? "(?<![A-Za-z0-9_])"
      : "";
    const rightBoundary = /[A-Za-z0-9_]$/.test(phrase)
      ? "(?![A-Za-z0-9_])"
      : "";
    return value.replace(
      new RegExp(`${leftBoundary}${escaped}${rightBoundary}`, "g"),
      replacement,
    );
  }

  function translateString(value) {
    const source = String(value ?? "");
    if (language !== "en") {
      const exact = chineseExactTranslations[source];
      if (exact) return exact;
      let translated = source;
      translated = translated
        .replace(/^BUY\s+/, "买入 ")
        .replace(/^SELL\s+/, "卖出 ")
        .replace(/^CAGR alpha\s*/, "CAGR 超额 ")
        .replace(/([+-]?\d+(?:\.\d+)?)pp\b/g, "$1 个百分点")
        .replace(/([+-]?\d+(?:\.\d+)?)x\b/g, "$1 倍");
      for (const [en, zh] of orderedChineseTranslations) {
        translated = replaceEnglishPhrase(translated, en, zh);
      }
      return translated;
    }
    if (!cjkPattern.test(source)) return source;
    let translated = source;
    for (const [zh, en] of orderedTranslations) {
      if (translated.includes(zh)) translated = translated.split(zh).join(en);
    }
    if (cjkPattern.test(translated)) {
      console.warn("[i18n] Untranslated Ontology text", source);
      return normalizeEnglishPunctuation(
        translated.replace(/[\u3400-\u9fff]+/g, "translation unavailable"),
      );
    }
    return normalizeEnglishPunctuation(translated);
  }

  function localizeTextNode(node) {
    const current = node.nodeValue || "";
    const stored = textSources.get(node);
    const source = stored && current === stored.rendered ? stored.source : current;
    const rendered = translateString(source);
    textSources.set(node, { source, rendered });
    if (current !== rendered) node.nodeValue = rendered;
  }

  function localizeAttributes(element) {
    const names = ["title", "aria-label", "placeholder"];
    let stored = attributeSources.get(element) || {};
    for (const name of names) {
      if (!element.hasAttribute?.(name)) continue;
      const current = element.getAttribute(name) || "";
      const previous = stored[name];
      const source = previous && current === previous.rendered ? previous.source : current;
      const rendered = translateString(source);
      stored = { ...stored, [name]: { source, rendered } };
      if (current !== rendered) element.setAttribute(name, rendered);
    }
    attributeSources.set(element, stored);
  }

  function localizeDom(target = root.document) {
    if (!target || applying) return;
    applying = true;
    try {
      if (target.nodeType === 3) {
        localizeTextNode(target);
        return;
      }
      if (target.nodeType === 1) localizeAttributes(target);
      const walker = root.document.createTreeWalker(
        target,
        root.NodeFilter.SHOW_ELEMENT | root.NodeFilter.SHOW_TEXT,
      );
      let node = walker.nextNode();
      while (node) {
        if (node.nodeType === 3) localizeTextNode(node);
        else localizeAttributes(node);
        node = walker.nextNode();
      }
    } finally {
      applying = false;
    }
  }

  function localizedGuruPath() {
    let candidate = "/";
    try {
      candidate = new URLSearchParams(root.location?.search || "").get("returnTo") || "/";
      if (candidate.startsWith("//")) candidate = "/";
      const parsed = new URL(candidate, root.location?.origin || "http://localhost");
      const sameOrigin = !root.location?.origin || parsed.origin === root.location.origin;
      if (!sameOrigin || parsed.pathname !== "/") candidate = "/";
      else {
        parsed.searchParams.set("lang", language);
        candidate = `${parsed.pathname}${parsed.search}${parsed.hash}`;
      }
    } catch (_) {
      candidate = "/";
    }
    if (candidate === "/") return `/?lang=${language}`;
    return candidate;
  }

  function renderLanguageControl() {
    if (!root.document) return;
    root.document.documentElement.lang = language === "en" ? "en" : "zh-CN";
    root.document.querySelectorAll("[data-language]").forEach((button) => {
      const value = button.dataset.language;
      button.classList.toggle("active", value === language);
      button.textContent = language === "en"
        ? (value === "zh" ? "Chinese" : "English")
        : (value === "zh" ? "中文" : "EN");
    });
    const backLink = root.document.querySelector(".guru-back-link");
    if (backLink) backLink.href = localizedGuruPath();
  }

  function setLanguage(nextLanguage, { updateUrl = true } = {}) {
    const next = languageCode(nextLanguage);
    if (language === next && !updateUrl) return;
    language = next;
    try {
      root.localStorage?.setItem("guru-language", language);
    } catch (_) {}
    if (updateUrl && root.location && root.history) {
      const url = new URL(root.location.href);
      url.searchParams.set("lang", language);
      root.history.replaceState(null, "", `${url.pathname}${url.search}${url.hash}`);
    }
    renderLanguageControl();
    localizeDom();
    root.dispatchEvent?.(new CustomEvent("ontology-language-change", {
      detail: { language },
    }));
  }

  function initializeDom() {
    try {
      const queryLanguage = new URLSearchParams(root.location?.search || "").get("lang");
      const savedLanguage = root.localStorage?.getItem("guru-language");
      language = languageCode(queryLanguage || savedLanguage);
    } catch (_) {}
    root.document.querySelectorAll("[data-language]").forEach((button) => {
      button.addEventListener("click", () => setLanguage(button.dataset.language));
    });
    renderLanguageControl();
    localizeDom();
    const observer = new MutationObserver((mutations) => {
      if (applying) return;
      for (const mutation of mutations) {
        if (mutation.type === "characterData") localizeDom(mutation.target);
        if (mutation.type === "attributes") localizeDom(mutation.target);
        mutation.addedNodes.forEach((node) => localizeDom(node));
      }
    });
    observer.observe(root.document.documentElement, {
      subtree: true,
      childList: true,
      characterData: true,
      attributes: true,
      attributeFilter: ["title", "aria-label", "placeholder"],
    });
  }

